/*
  WHEN EACH BUSINESS WENT ONTO BEASTY, from the project's own history.

    npx tsx tools/added-on.ts        (writes src/data/addedOn.ts)

  Every business is defined in code, so the day it first appeared in a commit
  is the day it was added. One pass over the commits that touched src/data,
  oldest first: the first added line that defines a business (`slug: '...'`,
  `seed('...'`, or an `id: 'b_...'`) dates it, in Pacific time. The CRM uses
  this to count businesses added per day and to date the leads it imports from
  the listings (Leon, 2026-10-11: the chart was "not right with what I'm
  adding"). Run it in each batch, after the new pages are committed.
*/
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { BRANDS } from '../src/data/brands'
import { ADDED_ON as BEFORE } from '../src/data/addedOn'

const ids = new Set(BRANDS.map((b) => b.id))
const git = (...args: string[]) => execFileSync('git', args, { encoding: 'utf8', maxBuffer: 1 << 28 })
const commits = git('log', '--reverse', '--format=%H %ct', '--', 'src/data')
  .trim()
  .split('\n')
  .map((l) => l.split(' '))
const day = (sec: number) => new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Los_Angeles', year: 'numeric', month: '2-digit', day: '2-digit' }).format(new Date(sec * 1000))

const DEF = /(?:slug:\s*|seed\(\s*)['"]([a-z0-9-]+)['"]|id:\s*['"](b_[a-z0-9]+)['"]/gi
const found = new Map<string, string>()
for (const [sha, ct] of commits) {
  const diff = git('show', '--unified=0', '--format=', sha, '--', 'src/data')
  for (const line of diff.split('\n')) {
    if (!line.startsWith('+') || line.startsWith('+++')) continue
    for (const m of line.matchAll(DEF)) {
      const id = m[2] ?? `b_${m[1].replace(/-/g, '')}`
      if (ids.has(id) && !found.has(id)) found.set(id, day(Number(ct)))
    }
  }
}

/* Not in any commit yet: a business being added in this batch, so today. A date
   already on file is kept, so a re-run never moves anything. Foodie creator pages
   (b_foodie…, generated from foodies.ts) are not businesses and stay undated. */
const today = day(Date.now() / 1000)
let fresh = 0
for (const id of ids) {
  if (found.has(id) || id.startsWith('b_foodie')) continue
  if (BEFORE[id]) found.set(id, BEFORE[id])
  else {
    found.set(id, today)
    fresh++
  }
}
if (fresh) console.log(`${fresh} not committed yet, dated today (${today})`)

const rows = [...found].sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]))
const out = `/*
  The day each business went onto BEASTY (Pacific time), from the commit that
  first defined it. GENERATED by tools/added-on.ts — do not edit by hand.
  ${found.size} of ${ids.size} businesses dated.
*/
export const ADDED_ON: Record<string, string> = {
${rows.map(([id, d]) => `  ${id}: '${d}',`).join('\n')}
}
`
writeFileSync(new URL('../src/data/addedOn.ts', import.meta.url), out)
console.log(`${found.size} of ${ids.size} businesses dated, ${commits.length} commits read`)
const missing = [...ids].filter((i) => !found.has(i))
if (missing.length) console.log('undated:', missing.slice(0, 20).join(', '), missing.length > 20 ? `… +${missing.length - 20}` : '')
