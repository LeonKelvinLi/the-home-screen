-- A transaction's now() is shared by its events. Keep an explicit insertion
-- order rather than sorting equal timestamps by random UUIDs.
ALTER TABLE trade_events ADD COLUMN event_order bigint GENERATED BY DEFAULT AS IDENTITY;

-- Repair the ordering of historical timestamp ties without changing event
-- content or timestamps: the terminal outcome follows its confirming action.
WITH ordered AS (
  SELECT id,row_number() OVER (
    ORDER BY created_at,
      CASE WHEN action IN ('completed','canceled','operator_completed','operator_canceled') THEN 1 ELSE 0 END,
      event_order
  ) AS position
  FROM trade_events
)
UPDATE trade_events e SET event_order=o.position FROM ordered o WHERE e.id=o.id;

SELECT setval(
  pg_get_serial_sequence('trade_events','event_order'),
  GREATEST(COALESCE((SELECT max(event_order) FROM trade_events),0),1),
  EXISTS(SELECT 1 FROM trade_events)
);
ALTER TABLE trade_events ADD CONSTRAINT trade_event_order_unique UNIQUE(event_order);
ALTER TABLE trade_events ALTER COLUMN created_at SET DEFAULT clock_timestamp();
